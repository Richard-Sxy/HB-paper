#!/usr/bin/env python3
"""Generate isolated negative/regression cases; never launch OpenFOAM or Docker.

Copies only the newly authored tests/cases/{oscillatoryChannel,amiCavity}.
Existing meshes may be reused, but solver outputs and logs are not copied.
Reruns replace only destinations marked as generated by this script.
"""
from pathlib import Path
import json
import re
import shutil

from generate_cases import write


ROOT = Path(__file__).resolve().parent / "cases"
MARKER = ".negative_cases_generated"


def copy_case(source_name, destination_name):
    source = ROOT / source_name
    target = ROOT / destination_name
    if target.exists():
        if not (target / MARKER).is_file():
            raise RuntimeError(f"Refusing to overwrite unmarked case: {target}")
        shutil.rmtree(target)

    def ignore(directory, names):
        skipped = {name for name in names if name.startswith("log.")}
        skipped.update(name for name in names if name in
                       {"verification.json", "postProcessing", "processor0", MARKER})
        if Path(directory) == source:
            skipped.update(name for name in names
                           if re.fullmatch(r"[+-]?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][+-]?\d+)?", name)
                           and name != "0")
        return skipped

    shutil.copytree(source, target, ignore=ignore)
    write(target / MARKER, "Generated by tests/negative_cases.py\n")
    return target


def set_entry(path, key, value):
    text = path.read_text(encoding="utf-8")
    pattern = rf"(?m)^(\s*{re.escape(key)}\s+)[^;]+;"
    text, count = re.subn(pattern, rf"\g<1>{value};", text)
    if count != 1:
        raise ValueError(f"Expected exactly one {key} entry in {path}")
    write(path, text)


def add_expectation(case, expectation):
    write(case / "regression.json", json.dumps(expectation, indent=2) + "\n")
    print(case)


def generate():
    failure = copy_case("oscillatoryChannel", "maxNewtonZero")
    set_entry(failure / "constant/HBProperties", "maxNewton", 0)
    add_expectation(failure, {
        "test": "nonconvergenceIsFailure", "expectedExitCode": 2,
        "mustNotExist": "1", "requiredLogText": "FAILED: no converged solution written",
        "reason": "Initial U=0 cannot satisfy nonzero forcing at all three phases."
    })

    checker = copy_case("oscillatoryChannel", "checkerboardChannel")
    metadata = json.loads((checker / "metadata.json").read_text())
    nx, ny = metadata["nx"], metadata["ny"]
    pressure = [1 if (i+j) % 2 == 0 else -1 for j in range(ny) for i in range(nx)]
    replacement = (f"internalField nonuniform List<scalar>\n{len(pressure)}\n(\n"
                   + "\n".join(map(str, pressure)) + "\n);\n")
    for phase in metadata["phases"]:
        path = checker / "0" / phase["name"] / "p"
        text, count = re.subn(r"internalField\s+uniform\s+[^;]+;\s*", replacement,
                             path.read_text(encoding="utf-8"))
        if count != 1:
            raise ValueError(f"Expected uniform initial pressure in {path}")
        write(path, text)
        velocity = checker / "0" / phase["name"] / "U"
        text, count = re.subn(r"internalField\s+uniform\s*\([^)]*\)\s*;",
                             "internalField uniform (0 0 0);", velocity.read_text())
        if count != 1:
            raise ValueError(f"Expected uniform initial velocity in {velocity}")
        write(velocity, text)
    add_expectation(checker, {
        "test": "checkerboardPressureSuppression", "expectedExitCode": 0,
        "initialPressure": "p(i,j)=(-1)^(i+j), cell numbering x-fastest",
        "initialVelocity": [0, 0, 0], "expectedKinematicPressure": 0,
        "pressureMaxAbsTolerance": 2e-5,
        "velocityCheck": "python3 tests/check_channel.py tests/cases/checkerboardChannel",
        "physicalAuditCheck": "python3 tests/check_results.py tests/cases/checkerboardChannel"
    })

    steady = copy_case("amiCavity", "steadyAmiCavity")
    set_entry(steady / "constant/HBProperties", "harmonics", 0)
    for root in (steady / "0", steady / "constant", steady / "system"):
        for child in root.iterdir():
            if child.is_dir() and re.fullmatch(r"phase[1-9]\d*", child.name):
                shutil.rmtree(child)
    metadata = json.loads((steady / "metadata.json").read_text())
    metadata["nPhases"] = 1
    metadata["phases"] = metadata["phases"][:1]
    metadata["scope"] = "H=0 steady nonlinear nonconformal AMI cavity"
    write(steady / "metadata.json", json.dumps(metadata, indent=2) + "\n")
    write(steady / "Allmesh", '#!/bin/sh\nset -eu\ncd "$(dirname "$0")"\n'
          'blockMesh -region phase0 > log.blockMesh.phase0 2>&1\n')
    (steady / "Allmesh").chmod(0o755)
    add_expectation(steady, {
        "test": "H0SteadyLimit", "expectedExitCode": 0,
        "expectedPhaseCount": 1, "requiredLogText": "CONVERGED: all-phase solution written",
        "maxMomentumTolerance": 1e-7, "maxContinuityTolerance": 1e-7,
        "maxAMIMassTolerance": 1e-10,
        "physicalAuditCheck": "python3 tests/check_results.py tests/cases/steadyAmiCavity"
    })


if __name__ == "__main__":
    generate()
